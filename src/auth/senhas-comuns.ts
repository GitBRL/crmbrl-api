const CONJUNTO = new Set(SENHAS_COMUNS);

/** A senha está na lista de senhas comuns (sem diferença de maiúsculas e acentos)? */
export function ehSenhaComum(senha: string): boolean {
  const normalizada = senha
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toLowerCase();
  return CONJUNTO.has(normalizada);
}

export const MENSAGEM_SENHA_COMUM =
  'é uma senha muito comum; escolha outra mais difícil de adivinhar';

/** Decorador de DTO: recusa senha da lista de senhas comuns (R2.12). */
export function SenhaNaoComum(opcoes?: ValidationOptions): PropertyDecorator {
  return (alvo, propriedade) => {
    registerDecorator({
      name: 'senhaNaoComum',
      target: alvo.constructor,
      propertyName: propriedade as string,
      options: { message: MENSAGEM_SENHA_COMUM, ...opcoes },
      validator: {
        validate: (valor: unknown) =>
          typeof valor !== 'string' || !ehSenhaComum(valor),
      },
    });
  };
}
